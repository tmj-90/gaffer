import type { z } from "zod";

import { TOOL_DESCRIPTIONS } from "./server.js";
import { toolSchemas, type ToolName } from "./tools.js";

/**
 * The README's MCP tool table, rendered from the code: every key of `toolSchemas`
 * (the tools the server registers), its arguments (`?` = optional) and the first
 * sentence of its coaching description. `node scripts/mcp-tools-doc.mjs` writes it
 * between the README markers and a test fails when the two drift — the hand-kept
 * list had fallen five tools behind.
 */
export const MCP_TOOLS_START = "<!-- mcp-tools:start -->";
export const MCP_TOOLS_END = "<!-- mcp-tools:end -->";

/** The lead sentence of a description: its bold opener, else up to the first ". ". */
export function leadSentence(description: string): string {
  const bold = /^\*\*(.+?)\*\*/.exec(description);
  const lead = bold ? (bold[1] as string) : (description.split(/(?<=\.)\s/)[0] as string);
  return lead.replace(/\|/g, "\\|").trim();
}

function argList(name: ToolName): string {
  const shape = toolSchemas[name] as Record<string, z.ZodTypeAny>;
  const args = Object.entries(shape).map(([k, s]) => `\`${k}${s.isOptional() ? "?" : ""}\``);
  return args.length > 0 ? args.join(", ") : "—";
}

export function renderMcpToolTable(): string {
  const names = Object.keys(toolSchemas) as ToolName[];
  const rows = names.map(
    (n) => `| \`${n}\` | ${argList(n)} | ${leadSentence(TOOL_DESCRIPTIONS[n])} |`,
  );
  return [
    MCP_TOOLS_START,
    `<!-- generated by scripts/mcp-tools-doc.mjs from src/mcp/tools.ts + src/mcp/server.ts — do not edit by hand -->`,
    "",
    `${names.length} tools:`,
    "",
    "| Tool | Arguments | What it is for |",
    "| --- | --- | --- |",
    ...rows,
    "",
    MCP_TOOLS_END,
  ].join("\n");
}

/** Replace the marked section of `readme` with the rendered table (throws if unmarked). */
export function spliceMcpToolTable(readme: string): string {
  const start = readme.indexOf(MCP_TOOLS_START);
  const end = readme.indexOf(MCP_TOOLS_END);
  if (start < 0 || end < start) {
    throw new Error(`README has no ${MCP_TOOLS_START} … ${MCP_TOOLS_END} section`);
  }
  return readme.slice(0, start) + renderMcpToolTable() + readme.slice(end + MCP_TOOLS_END.length);
}
